defmodule EventpageWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :eventpage

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  #
  # No :domain here. A cookie scoped to your own domain is dropped by
  # the browser on every custom domain, and then LiveView can't mount.
  @session_options [
    store: :cookie,
    key: "_eventpage_key",
    signing_salt: "JngJpyG7",
    same_site: "Lax"
  ]

  # The default check_origin only accepts your own host (url: [host: ...])
  # and refuses the socket on every custom domain. Ask the database
  # instead. Sockets are dispatched before the plugs below run, so
  # EventpageWeb.HostRouter never sees these requests.
  @check_origin {EventpageWeb.OriginCheck, :allowed?, []}

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options], check_origin: @check_origin],
    longpoll: [connect_info: [session: @session_options], check_origin: @check_origin]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :eventpage,
    gzip: not code_reloading?,
    only: EventpageWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :eventpage
  end

  # Before the host check: load balancers call it by IP address.
  plug EventpageWeb.HealthCheck

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  # Instead of `plug EventpageWeb.Router`: checks the proxy token and
  # picks EventpageWeb.Router or EventpageWeb.SiteRouter by hostname.
  plug EventpageWeb.HostRouter
end
